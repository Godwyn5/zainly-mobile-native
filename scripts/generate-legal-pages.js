#!/usr/bin/env node
// ─── generate-legal-pages.js ──────────────────────────────────────────────────
// Generates web-legal/privacy.html and web-legal/terms.html from the single
// editorial source of truth: src/legal-content/privacy.json and terms.json.
//
// This script is the ONLY place that should ever produce those HTML files.
// Never hand-edit web-legal/privacy.html or web-legal/terms.html — edit the
// JSON files instead, then re-run this script.
//
// Usage:
//   node scripts/generate-legal-pages.js          → (re)generate the HTML files
//   node scripts/generate-legal-pages.js --check  → verify HTML is up to date
//                                                    with the JSON (exits 1 if
//                                                    stale), without writing.
//
// No dependencies, no framework — plain Node.js `fs`/`path` only. Pure static
// output: no JavaScript is embedded in the generated pages.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONTENT_DIR = path.join(ROOT, 'src', 'legal-content');
const OUTPUT_DIR = path.join(ROOT, 'web-legal');

const PAGES = [
  { jsonFile: 'privacy.json', htmlFile: 'privacy.html' },
  { jsonFile: 'terms.json', htmlFile: 'terms.html' },
];

const AUTO_GENERATED_BANNER =
  '<!--\n' +
  '  AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.\n' +
  '  Generated by scripts/generate-legal-pages.js from\n' +
  '  src/legal-content/{privacy,terms}.json (the single editorial source of\n' +
  '  truth for all Zainly legal text). To change this content, edit the JSON\n' +
  '  file, then run: npm run legal:build\n' +
  '-->';

// ─── HTML escaping ─────────────────────────────────────────────────────────────
// Minimal, explicit escaping. Never interpolate raw JSON strings into HTML.
function escapeHtml(input) {
  return String(input)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function renderSection(section) {
  return (
    '      <section class="section">\n' +
    `        <h2>${escapeHtml(section.title)}</h2>\n` +
    `        <p>${escapeHtml(section.content)}</p>\n` +
    '      </section>'
  );
}

function renderPage(content, htmlFile) {
  const sectionsHtml = content.sections.map(renderSection).join('\n\n');
  const pageTitle = escapeHtml(`${content.title} — Zainly`);
  const heading = escapeHtml(content.title);
  const lastUpdated = escapeHtml(content.lastUpdated);
  // Contact email is data-driven too — never hardcoded here.
  const contactEmail = escapeHtml(content.contactEmail);

  return `<!DOCTYPE html>
<html lang="fr">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${pageTitle}</title>
  <meta name="description" content="${pageTitle}">
  <link rel="stylesheet" href="styles.css">
</head>
<body>
${AUTO_GENERATED_BANNER}
  <div class="container">
    <header>
      <a href="index.html" class="back-link">← Retour</a>
      <h1>${heading}</h1>
    </header>

    <main>
${sectionsHtml}
    </main>

    <footer>
      <p class="updated">Dernière mise à jour : ${lastUpdated} — Contact : <a href="mailto:${contactEmail}">${contactEmail}</a></p>
    </footer>
  </div>
</body>
</html>
`;
}

function loadContent(jsonFile) {
  const raw = fs.readFileSync(path.join(CONTENT_DIR, jsonFile), 'utf8');
  return JSON.parse(raw);
}

function main() {
  const checkOnly = process.argv.includes('--check');
  let stale = false;

  for (const { jsonFile, htmlFile } of PAGES) {
    const content = loadContent(jsonFile);
    const generated = renderPage(content, htmlFile);
    const outputPath = path.join(OUTPUT_DIR, htmlFile);

    if (checkOnly) {
      const existing = fs.existsSync(outputPath)
        ? fs.readFileSync(outputPath, 'utf8')
        : null;
      if (existing !== generated) {
        stale = true;
        console.error(`[legal:check] STALE: ${htmlFile} does not match ${jsonFile}. Run "npm run legal:build".`);
      } else {
        console.log(`[legal:check] OK: ${htmlFile} is up to date with ${jsonFile}.`);
      }
    } else {
      fs.writeFileSync(outputPath, generated, 'utf8');
      console.log(`[legal:build] Generated ${path.relative(ROOT, outputPath)} from ${path.relative(ROOT, path.join(CONTENT_DIR, jsonFile))}`);
    }
  }

  if (checkOnly && stale) {
    process.exit(1);
  }
}

main();
